export const bySlug = (slug) => products.find((p) => p.slug === slug)

export const related = (product, n = 4) =>
  products
    .filter((p) => p.id !== product.id)
    .map((p) => ({
      p,
      score: (p.category === product.category ? 3 : 0) + (p.gender === product.gender ? 2 : 0),
    }))
    .sort((a, b) => b.score - a.score || b.p.rating - a.p.rating)
    .slice(0, n)
    .map((x) => x.p)
